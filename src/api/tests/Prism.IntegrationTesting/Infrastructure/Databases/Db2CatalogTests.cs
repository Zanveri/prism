    /// <summary>
    /// Uma conta que não pode ler o catálogo: a conta comum do contêiner, com `SYSCAT.CHECKS` tirado de `PUBLIC` durante o teste. A
    /// resposta das restrições de conferência é a recusa do Db2 (SQL0551N), e não uma exceção; as colunas seguem respondendo.
    /// </summary>
    [Test]
    public async Task Catalog_ForAnAccountThatCannotReadIt_ReturnsTheRefusalOfTheDatabase()
    {
        await using var admin = await OpenAsync();
        await RunAsync(admin, "REVOKE SELECT ON TABLE SYSCAT.CHECKS FROM PUBLIC");
        try
        {
            await using var reader = await OpenAsync(await Db2Singleton.GetReaderSettingsAsync());
            var checks = await reader.GetChecksAsync(_schema, "CONFERIDA", CancellationToken.None);
            var columns = await reader.GetColumnsAsync(_schema, "CONFERIDA", CancellationToken.None);

            Assert.That(checks.IsFailure, Is.True);
            Assert.That(checks.Error.Kind, Is.EqualTo(EDatabaseFailure.ExecutionFailed));
            Assert.That(checks.Error.Message, Does.Contain("SQL0551N").And.Contain("SYSCAT.CHECKS"));
            Assert.That(checks.Error.SqlState, Is.EqualTo("42501"));
            Assert.That(Value(columns).Select(column => column.Name), Is.EqualTo(new[] { "PRECO", "QUANTIDADE" }));
        }
        finally
        {
            await admin.ExecuteAsync("GRANT SELECT ON TABLE SYSCAT.CHECKS TO PUBLIC", CancellationToken.None);
        }
    }

    protected override async Task<string> CreateLargeSchemaAsync()
    {
        var schema = $"DIAGRAMA_{Guid.NewGuid():N}"[..18].ToUpperInvariant();
        await using var connection = await OpenAsync();
        await RunAsync(connection, $"CREATE SCHEMA {schema}", $@"BEGIN
                                                                     DECLARE I INTEGER DEFAULT 1;

                                                                     WHILE I <= 300 DO
                                                                         EXECUTE IMMEDIATE 'CREATE TABLE {schema}.T' || I || ' (ID INTEGER NOT NULL PRIMARY KEY, NOME VARCHAR(40), REF_A INTEGER, REF_B INTEGER)';
                                                                         SET I = I + 1;
                                                                     END WHILE;

                                                                     SET I = 2;
                                                                     WHILE I <= 300 DO
                                                                         EXECUTE IMMEDIATE 'ALTER TABLE {schema}.T' || I || ' ADD CONSTRAINT FA_' || I || ' FOREIGN KEY (REF_A) REFERENCES {schema}.T' || (I - 1) || ' (ID)';
                                                                         SET I = I + 1;
                                                                     END WHILE;

                                                                     SET I = 101;
                                                                     WHILE I <= 201 DO
                                                                         EXECUTE IMMEDIATE 'ALTER TABLE {schema}.T' || I || ' ADD CONSTRAINT FB_' || I || ' FOREIGN KEY (REF_B) REFERENCES {schema}.T' || (I - 100) || ' (ID)';
                                                                         SET I = I + 1;
                                                                     END WHILE;
                                                                 END");

        return schema;
    }

    protected override async Task DropLargeSchemaAsync(string schema)
    {
        await using var connection = await OpenAsync();
        await RunAsync(connection, $@"BEGIN
                                          DECLARE I INTEGER DEFAULT 300;

                                          WHILE I >= 1 DO
                                              EXECUTE IMMEDIATE 'DROP TABLE {schema}.T' || I;
                                              SET I = I - 1;
                                          END WHILE;
                                      END", $"DROP SCHEMA {schema} RESTRICT");
    }

    private static bool SameNames(SchemaObjectNamesInfo left, SchemaObjectNamesInfo right)
        => (left.Name, left.IsSystem) == (right.Name, right.IsSystem) && left.Tables.SequenceEqual(right.Tables) && left.Views.SequenceEqual(right.Views);

    private static string Quote(string identifier)
        => $"\"{identifier.Replace("\"", "\"\"")}\"";
