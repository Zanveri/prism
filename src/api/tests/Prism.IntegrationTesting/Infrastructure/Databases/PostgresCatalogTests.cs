    /// <summary>RN-CAT-002: as cinco regras, ao excluir e ao atualizar; a chave composta; e a que aponta para a própria tabela.</summary>
    [Test]
    public async Task ForeignKeys_ReportBothRules()
    {
        await using var connection = await OpenAsync();

        var children = Value(await connection.GetForeignKeysAsync(_schema, "filho", CancellationToken.None));
        var parent = Value(await connection.GetForeignKeysAsync(_schema, "pai", CancellationToken.None));

        Assert.That(children.Select(key => (key.Name, string.Join(",", key.Columns), string.Join(",", key.ReferencedColumns), key.OnDelete, key.OnUpdate)), Is.EqualTo(new[]
        {
            ("fk_a", "pai_id", "id", "noAction", "restrict"),
            ("fk_b", "pai_id", "id", "restrict", "cascade"),
            ("fk_c", "pai_id", "id", "cascade", "setNull"),
            ("fk_d", "pai_id,pai_codigo", "id,codigo", "setNull", "setDefault"),
            ("fk_e", "pai_id", "id", "setDefault", "noAction")
        }));
        Assert.That(children.Select(key => (key.ReferencedSchema, key.ReferencedTable)), Is.All.EqualTo((_schema, "pai")));
        Assert.That(parent, Is.EqualTo(new[] { new ForeignKeyInfo("fk_pai_superior", ["superior"], _schema, "pai", ["id"], "noAction", "noAction") }).Using<ForeignKeyInfo>(SameForeignKey));
    }

