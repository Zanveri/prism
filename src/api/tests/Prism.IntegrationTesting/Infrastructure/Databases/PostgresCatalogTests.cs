    public async Task ViewDefinition_ReturnsTheTextTheDatabaseKeeps()
    {
        await using var connection = await OpenAsync();

        var shortView = Value(await connection.GetViewDefinitionAsync(_schema, "resumo", CancellationToken.None));
        var longView = Value(await connection.GetViewDefinitionAsync(_schema, "longa", CancellationToken.None));
