    /// <summary>
    /// Nomes com maiúsculas e minúsculas, espaço e aspas, no esquema, na tabela, na coluna e nas restrições, e outra tabela de mesmo
    /// nome a não ser pelas maiúsculas: cada consulta acha a tabela certa, e nada quebra.
    /// </summary>
    [Test]
    public async Task Catalog_OfNamesWithCaseSpacesAndQuotes_FindsTheRightObjects()
    {
        const string schema = "Esq \"M\" 'x'";
        const string table = "Tab \"Q\" 'y'";
        const string twin = "tab \"q\" 'y'";
        const string column = "Col \"C\" 'z'";
        await using var connection = await OpenAsync();
        await RunAsync(connection,
            $"CREATE SCHEMA {Quote(schema)}",
            $"CREATE TABLE {Quote(schema)}.{Quote(table)} ({Quote(column)} integer DEFAULT 7 CONSTRAINT {Quote("Pk \"P\" 'p'")} PRIMARY KEY, CONSTRAINT {Quote("Ck \"K\" 'w'")} CHECK ({Quote(column)} > 0))",
            $"CREATE TABLE {Quote(schema)}.{Quote(twin)} (outra integer, ref integer, CONSTRAINT {Quote("Fk \"F\" 'v'")} FOREIGN KEY (ref) REFERENCES {Quote(schema)}.{Quote(table)} ({Quote(column)}) ON DELETE CASCADE)",
            $"CREATE VIEW {Quote(schema)}.{Quote("Vis \"V\" 'u'")} AS SELECT {Quote(column)} FROM {Quote(schema)}.{Quote(table)}");
        try
        {
            var columns = Value(await connection.GetColumnsAsync(schema, table, CancellationToken.None));
            var twinColumns = Value(await connection.GetColumnsAsync(schema, twin, CancellationToken.None));
            var checks = Value(await connection.GetChecksAsync(schema, table, CancellationToken.None));
            var twinChecks = Value(await connection.GetChecksAsync(schema, twin, CancellationToken.None));
            var referencedBy = Value(await connection.GetReferencingForeignKeysAsync(schema, table, CancellationToken.None));
            var foreignKeys = Value(await connection.GetForeignKeysAsync(schema, twin, CancellationToken.None));
            var view = Value(await connection.GetViewDefinitionAsync(schema, "Vis \"V\" 'u'", CancellationToken.None));
            var diagram = Value(await connection.GetDiagramAsync(schema, CancellationToken.None));
            var schemas = Value(await connection.GetSchemasAsync(CancellationToken.None));

            Assert.That(columns, Is.EqualTo(new[] { new ColumnInfo(column, "integer", false, true, 1, "7", null) }));
            Assert.That(twinColumns.Select(item => item.Name), Is.EqualTo(new[] { "outra", "ref" }));
            Assert.That(checks, Is.EqualTo(new[] { new CheckConstraintInfo("Ck \"K\" 'w'", $"{Quote(column)} > 0") }));
            Assert.That(twinChecks, Is.Empty);
            Assert.That(referencedBy.Select(key => (key.Name, key.ReferencingSchema, key.ReferencingTable, key.ReferencedColumns.Single(), key.OnDelete)), Is.EqualTo(new[] { ("Fk \"F\" 'v'", schema, twin, column, "cascade") }));
            Assert.That(foreignKeys.Select(key => (key.Name, key.ReferencedSchema, key.ReferencedTable)), Is.EqualTo(new[] { ("Fk \"F\" 'v'", schema, table) }));
            Assert.That(view.Definition, Is.EqualTo($" SELECT {Quote(column)}\n   FROM {Quote(schema)}.{Quote(table)};"));
            Assert.That(diagram.Tables.Select(item => item.Name), Is.EqualTo(new[] { table, twin }));
            Assert.That(schemas.Single(item => item.Name == schema).Tables, Is.EqualTo(2));
        }
        finally
        {
            await connection.ExecuteAsync($"DROP SCHEMA {Quote(schema)} CASCADE", CancellationToken.None);
        }
    }

    /// <summary>
    /// Uma conta que não pode ler o catálogo: num banco só do teste, `pg_constraint` deixa de ser legível por todos. A resposta das
    /// consultas que a leem é a recusa do banco, com o SQLSTATE dele, e não uma exceção; as que não a leem seguem respondendo.
    /// </summary>
    [Test]
    public async Task Catalog_ForAnAccountThatCannotReadIt_ReturnsTheRefusalOfTheDatabase()
    {
        var suffix = Guid.NewGuid().ToString("N")[..12];
        var database = $"restrito_{suffix}";
        var role = $"leitor_{suffix}";
        var password = Convert.ToHexString(RandomNumberGenerator.GetBytes(16));
        await using (var admin = await OpenAsync())
            await RunAsync(admin, $"CREATE DATABASE {database}", $"CREATE ROLE {role} LOGIN PASSWORD '{password}'");

        try
        {
            await using (var owner = await OpenAsync(Settings with { Database = database }))
                await RunAsync(owner, "CREATE TABLE conferida (id integer CHECK (id > 0))", "REVOKE SELECT ON pg_catalog.pg_constraint FROM PUBLIC");

            await using var reader = await OpenAsync(Settings with { Database = database, UserName = role, Password = password });
            var checks = await reader.GetChecksAsync("public", "conferida", CancellationToken.None);
            var foreignKeys = await reader.GetForeignKeysAsync("public", "conferida", CancellationToken.None);
            var columns = await reader.GetColumnsAsync("public", "conferida", CancellationToken.None);

            Assert.That(checks.IsFailure, Is.True);
            Assert.That(checks.Error.Kind, Is.EqualTo(EDatabaseFailure.ExecutionFailed));
            Assert.That(checks.Error.Message, Is.EqualTo("permission denied for table pg_constraint"));
            Assert.That(checks.Error.SqlState, Is.EqualTo("42501"));
            Assert.That(foreignKeys.Error.SqlState, Is.EqualTo("42501"));
            Assert.That(Value(columns).Select(column => column.Name), Is.EqualTo(new[] { "id" }));
        }
        finally
        {
            await using var admin = await OpenAsync();
            await admin.ExecuteAsync($"DROP DATABASE {database} WITH (FORCE)", CancellationToken.None);
            await admin.ExecuteAsync($"DROP ROLE {role}", CancellationToken.None);
        }
    }

    protected override async Task<string> CreateLargeSchemaAsync()
    {
        var schema = $"diagrama_{Guid.NewGuid():N}"[..21];
        await using var connection = await OpenAsync();
        await RunAsync(connection, $"CREATE SCHEMA {schema}", $@"DO $$
                                                                BEGIN
                                                                    FOR i IN 1..300 LOOP
                                                                        EXECUTE format('CREATE TABLE {schema}.t%s (id integer PRIMARY KEY, nome varchar(40), ref_a integer, ref_b integer)', i);
                                                                    END LOOP;
                                                                    FOR i IN 2..300 LOOP
                                                                        EXECUTE format('ALTER TABLE {schema}.t%s ADD CONSTRAINT fa_%s FOREIGN KEY (ref_a) REFERENCES {schema}.t%s (id)', i, i, i - 1);
                                                                    END LOOP;
                                                                    FOR i IN 101..201 LOOP
                                                                        EXECUTE format('ALTER TABLE {schema}.t%s ADD CONSTRAINT fb_%s FOREIGN KEY (ref_b) REFERENCES {schema}.t%s (id)', i, i, i - 100);
                                                                    END LOOP;
                                                                END $$");

        return schema;
    }

    protected override async Task DropLargeSchemaAsync(string schema)
    {
