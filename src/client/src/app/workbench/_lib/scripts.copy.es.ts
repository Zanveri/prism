function folderContents(folders: number, scripts: number): string {
  const parts = [folders === 0 ? null : folders === 1 ? "1 subcarpeta" : `${folders.toLocaleString("es")} subcarpetas`, scripts === 0 ? null : scripts === 1 ? "1 script" : `${scripts.toLocaleString("es")} scripts`];
  return parts.filter((part) => part !== null).join(" y ");
}

