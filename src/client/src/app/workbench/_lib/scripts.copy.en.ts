function folderContents(folders: number, scripts: number): string {
  const parts = [folders === 0 ? null : folders === 1 ? "1 subfolder" : `${folders.toLocaleString("en")} subfolders`, scripts === 0 ? null : scripts === 1 ? "1 script" : `${scripts.toLocaleString("en")} scripts`];
  return parts.filter((part) => part !== null).join(" and ");
}

